    #[test]
    fn cases_and_bases() {
        assert_eq!(to_upper_rune('a'), 'A');
        assert_eq!(to_upper_rune('ā'), 'Ā');
        assert_eq!(to_upper_rune('ÿ'), 'Ÿ');
        assert_eq!(to_upper_rune('1'), '1');
        assert_eq!(to_lower_rune('Σ'), 'σ');
        assert_eq!(to_lower_rune('Ā'), 'ā');
        assert_eq!(to_title_rune('\u{1c6}'), '\u{1c5}');
        assert_eq!(to_base_rune('é'), 'e');
        assert_eq!(to_base_rune('À'), 'A');
        assert_eq!(to_base_rune('x'), 'x');
        assert!(is_base_rune('x') && !is_base_rune('é'));
    }
