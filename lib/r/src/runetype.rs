//! The kinds and cases of runes, as Plan 9's `isalpharune(2)` has them:
//! the tables are Plan 9's (`libc/port/runetypebody-6.2.0.h`, from
//! Unicode 6.2, and `runebase.c`), and are searched as its
//! `_runebsearch` does. [`is_space_rune`](crate::utf::is_space_rune) is
//! in [`utf`](crate::utf).
//!
//! A table of ranges holds pairs (first, last), or triples with a third
//! entry, the change of case plus 2^20; one of "alternate" ranges, every
//! other rune from the first; one of singles, runes or pairs.

// The tables are as Plan 9 writes them.
#![allow(clippy::unreadable_literal)]

/// What a case table's change is offset by.
const BIAS: u32 = 1 << 20;

/// The entry of `ne` runes in `t` whose first is the greatest at or
/// below `c` (Plan 9's `_runebsearch`).
fn bsearch(c: u32, table: &[u32], ne: usize) -> Option<&[u32]> {
    let mut t = table;
    let mut n = t.len() / ne;
    while n > 1 {
        let half = n / 2;
        let mid = &t[half * ne..];
        if c >= mid[0] {
            t = mid;
            n -= half;
        } else {
            n = half;
        }
    }
    (n > 0 && c >= t[0]).then(|| &t[..ne])
}

fn in_ranges(c: u32, t: &[u32]) -> bool {
    bsearch(c, t, 2).is_some_and(|p| c <= p[1])
}

fn in_alternates(c: u32, t: &[u32]) -> bool {
    bsearch(c, t, 2).is_some_and(|p| c <= p[1] && (c - p[0]) & 1 == 0)
}

fn in_singles(c: u32, t: &[u32]) -> bool {
    bsearch(c, t, 1).is_some_and(|p| c == p[0])
}

/// The class membership test of Plan 9's `is*rune`: ranges, alternate
/// ranges, then singles.
fn is(c: char, ranges: &[u32], alternates: &[u32], singles: &[u32]) -> bool {
    let c = u32::from(c);
    in_ranges(c, ranges) || in_alternates(c, alternates) || in_singles(c, singles)
}

/// The case mapping of Plan 9's `to*rune`.
fn to(c: char, ranges: &[u32], alternates: &[u32], singles: &[u32]) -> char {
    let u = u32::from(c);
    let delta = if let Some(e) = bsearch(u, ranges, 3).filter(|e| u <= e[1]) {
        e[2]
    } else if let Some(e) = bsearch(u, alternates, 3).filter(|e| u <= e[1] && (u - e[0]) & 1 == 0) {
        e[2]
    } else if let Some(e) = bsearch(u, singles, 2).filter(|e| u == e[0]) {
        e[1]
    } else {
        return c;
    };
    char::from_u32(u.wrapping_add(delta).wrapping_sub(BIAS)).unwrap_or(c)
}

#[must_use]
pub fn is_digit_rune(c: char) -> bool {
    in_ranges(u32::from(c), &ISDIGITR)
}

#[must_use]
pub fn is_alpha_rune(c: char) -> bool {
    is(c, &ISALPHAR, &[], &ISALPHAS)
}

#[must_use]
pub fn is_upper_rune(c: char) -> bool {
    is(c, &ISUPPERR, &ISUPPERP, &ISUPPERS)
}

#[must_use]
pub fn is_lower_rune(c: char) -> bool {
    is(c, &ISLOWERR, &ISLOWERP, &ISLOWERS)
}

#[must_use]
pub fn is_title_rune(c: char) -> bool {
    is(c, &ISTITLER, &ISTITLEP, &ISTITLES)
}

#[must_use]
pub fn to_upper_rune(c: char) -> char {
    to(c, &TOUPPERR, &TOUPPERP, &TOUPPERS)
}

#[must_use]
pub fn to_lower_rune(c: char) -> char {
    to(c, &TOLOWERR, &TOLOWERP, &TOLOWERS)
}

#[must_use]
pub fn to_title_rune(c: char) -> char {
    to(c, &TOTITLER, &TOTITLEP, &TOTITLES)
}

/// The letter `c` is an accented form of, or `c` (Plan 9's `tobaserune`).
#[must_use]
pub fn to_base_rune(c: char) -> char {
    let u = u32::from(c);
    match bsearch(u, &BASE2, 2) {
        Some(e) if u == e[0] => char::from_u32(e[1]).unwrap_or(c),
        _ => c,
    }
}

#[must_use]
pub fn is_base_rune(c: char) -> bool {
    to_base_rune(c) == c
}

